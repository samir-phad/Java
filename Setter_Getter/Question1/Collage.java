public class Collage{

	private String clgName;
	private int clgId;
	private String clgAddr;

public void setClg(String clgn){
	this.clgName = clgn;
}
public String getClg(){
	return clgName;
}

public void setClgid(int id){
	this.clgId = id;
}
public int getClgid(){
	return clgId;
}

public void setClgAddr(String add){
	this.clgAddr = add;
}
public String getClgAddr(){
	return clgAddr;
}
}