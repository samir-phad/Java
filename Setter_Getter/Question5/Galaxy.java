public class Galaxy{


	private String gName;
	private double gArea;
	private long gDistance;


	public void setGname(String name){
	this.gName = name;
	}
	
	public String getGname(){
	return gName;
	}

	public double setGarea(double area){
	this.gArea = area;
	}
	
	public double getGarea(){
	return gArea;
	}

	public void setGdistance(long distance){
	this.gDistance = distance;
	}
	
	public long getGdistance(){
	return gDistance;
	}

}