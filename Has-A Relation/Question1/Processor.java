public class Processor{

	private int pid;
	private String type;
	private Brand brand;


public void setPid(int id){
	this.pid = id;
}
public int getPid(){
	return pid;
}

public void setType(String tp){
	this.type = tp;
}
public String getType(){
	return type;
}

public void setBrand(Brand bd){
	this.brand = bd;
}
public Brand getBrand(){
	return brand;
}



}