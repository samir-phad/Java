public class Brand {

	private int bid; 
	private String brandName;
	private String country;

public void setBid(int id){
	this.bid = id;
}
public int getBid(){
	return bid;
}

public void setBname(String nm){
	this.brandName = nm;
}
public String getBname(){
	return brandName;
}

public void setCountry(String cty){
	this.country = cty;
}
public String getCountry(){
	return country;
}
}