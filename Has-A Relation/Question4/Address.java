public class Address{

	private int aid;
	private String city;
	private String state;

	public void setAid(int id){
		this.aid = id;
	}
	public int getAid(){
		return aid;
	}

	public void setCity(String cy){
		this.city = cy;
	}
	public String getCity(){
		return city;
	}

	public void setState(String st){
		this.state = st;
	}
	public String getState(){
		return state;
	}

}